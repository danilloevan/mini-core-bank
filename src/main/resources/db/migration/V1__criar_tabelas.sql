-- V1: CRIACAO DAS TABELAS DO SISTEMA BANCARIO (MINI CORE BANK - POO UFC)
-- ============================================================================

-- 1. Tabela de Agencias
CREATE TABLE agencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(10) NOT NULL UNIQUE,
    nome VARCHAR(120) NOT NULL,
    cidade VARCHAR(80) NOT NULL
);

-- 2. Tabela de Clientes (Heranca Single Table: PF e PJ + Endereco Embutido)
CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_cliente VARCHAR(10) NOT NULL,
    nome VARCHAR(150) NOT NULL,
    documento VARCHAR(20) NOT NULL UNIQUE,
    email VARCHAR(120) NOT NULL,
    -- Atributos especificos das subclasses (PessoaFisica / PessoaJuridica)
    data_nascimento DATE,
    razao_social VARCHAR(150),
    -- Atributos de Endereco (Composicao @Embedded)
    logradouro VARCHAR(150) NOT NULL,
    cidade VARCHAR(80) NOT NULL,
    uf VARCHAR(2) NOT NULL,
    cep VARCHAR(15) NOT NULL
);

-- 3. Tabela de Contas (Heranca Single Table: CORRENTE e EMPRESARIAL)
CREATE TABLE contas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_conta VARCHAR(20) NOT NULL,
    numero_conta VARCHAR(20) NOT NULL UNIQUE,
    saldo NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    status VARCHAR(20) NOT NULL DEFAULT 'ATIVA',
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    agencia_id BIGINT NOT NULL REFERENCES agencias(id)
);

-- 4. Tabela de Chaves PIX
CREATE TABLE chaves_pix (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL,
    valor VARCHAR(120) NOT NULL UNIQUE,
    conta_id BIGINT NOT NULL REFERENCES contas(id)
);

-- 5. Tabela de Transacoes (Heranca Single Table: DEPOSITO, SAQUE, PIX, TED + Comprovante Embutido)
CREATE TABLE transacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_transacao VARCHAR(20) NOT NULL,
    valor NUMERIC(15, 2) NOT NULL,
    tarifa NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    data_hora TIMESTAMP NOT NULL,
    descricao VARCHAR(255),
    conta_origem_id BIGINT REFERENCES contas(id),
    conta_destino_id BIGINT REFERENCES contas(id),
    -- Atributos especificos das subclasses
    canal_deposito VARCHAR(60),
    terminal_atm VARCHAR(60),
    chave_pix_destino VARCHAR(120),
    end_to_end_id VARCHAR(60),
    codigo_banco_destino VARCHAR(10),
    -- Atributos de ComprovanteTransacao (Composicao @Embedded)
    codigo_autenticacao VARCHAR(60) NOT NULL,
    resumo_operacao VARCHAR(255) NOT NULL,
    comprovante_emitido_em TIMESTAMP NOT NULL
);
